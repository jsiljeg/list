async function fetchLive(url) {
  const r = await fetch(url + (url.includes("?") ? "&" : "?") + "t=" + Date.now(), { cache: "no-store" });
  return r;
}

async function site(dir, now = new Date()) {
  const out = path.join(dir, "cjenik");
  fs.mkdirSync(out, { recursive: true });
  const live = process.env.CJENIK_LIVE === "none" ? null : (process.env.CJENIK_LIVE || LIVE);
  let prev = null;
  const carry = {};
  if (live) {
    const r = await fetchLive(`${live}/cjenik/manifest.json`);
    if (r.status === 404) console.log("cjenik: no live manifest — starting the archive");
    else if (!r.ok) throw new Error(`cjenik: live manifest answered ${r.status}; refusing to drop the archive`);
    else {
      prev = await r.json();
      for (const f of prev.files || [])
        for (const ext of ["csv", "xml"]) {
          const rr = await fetchLive(`${live}/cjenik/${f.base}.${ext}`);
          if (!rr.ok) throw new Error(`cjenik: archived ${f.base}.${ext} answered ${rr.status}`);
          carry[`${f.base}.${ext}`] = await rr.text();
        }
    }
  }
  const r = rows();
  const { manifest, changed, stamp } = nextManifest(prev, digest(r), now, r.length);
  const cur = manifest.files.find((f) => !f.replaced);
  if (changed) {
    carry[`${cur.base}.csv`] = csv(r);
    carry[`${cur.base}.xml`] = xml(r, stamp);
  }
  for (const f of manifest.files)
    for (const ext of ["csv", "xml"]) fs.writeFileSync(path.join(out, `${f.base}.${ext}`), carry[`${f.base}.${ext}`]);
  fs.writeFileSync(path.join(out, "cjenik.csv"), carry[`${cur.base}.csv`]);
  fs.writeFileSync(path.join(out, "cjenik.xml"), carry[`${cur.base}.xml`]);
  fs.writeFileSync(path.join(out, "manifest.json"), JSON.stringify(manifest, null, 1) + "\n");
  fs.writeFileSync(path.join(out, "index.html"), indexHtml(manifest));
  console.log(`cjenik: ${r.length} stavki, ${changed ? "new file " + cur.base : "unchanged"}; ${manifest.files.length - 1} replaced file(s) still published`);
}

async function main() {
  const i = process.argv.indexOf("--site");
  if (i > 0) { await site(process.argv[i + 1]); return 0; }
  const r = rows();
  process.stdout.write(csv(r));
  console.error(`${r.length} stavki, ${digest(r)}`);
  return 0;
}

