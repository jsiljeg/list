export const ISSUER = {
  obveznik: "Apelacija d.o.o.",
  oib: "30290222993",                       /* fininfo.hr / companywall.hr, check digit valid */
  objekt: "Restoran Theatrium by Filho",
  adresa: "Teslina 7, 10000 Zagreb",
  /* The sales point in the file name: its kind (as the hospitality rules
     classify it), address, and the till's own code for the premises — the
     "P3" in every fiscal bill number this restaurant issues. */
  mjesto: "RESTORAN_TESLINA_7_ZAGREB_P3",
};
export const RETAIN_DAYS = 15;
export const LIVE = "https://theatrium.list.devinos.hr";

const hideNorm = (s) => String(s == null ? "" : s).trim().toLowerCase();
/* The same test as hiddenTest() in js/app.js: a rule hides by name, optionally
   narrowed by producer, format and glass/bottle. */
export function hiddenTest(rules) {
  const rs = (Array.isArray(rules) ? rules : []).filter((r) => r && r.name);
  return (item, secId) => rs.some((r) =>
    hideNorm(r.name) === hideNorm(item.name) &&
    (!r.producer || hideNorm(r.producer) === hideNorm(item.producer)) &&
    (r.vol == null || Number(r.vol) === item.vol) &&
    (!r.where || (r.where === "glass" ? secId === "glass" : secId.startsWith("bottle"))));
}

/** The litres a price is quoted for, or null when the data has never said
 *  (a spirit's pour): never invented. */
function litres(sec, cat, item) {
  const m = String(cat.serving || "").match(/^([\d,.]+)\s*l$/);
  if (m) return Number(m[1].replace(",", "."));
  if (item.vol) return item.vol;
  return sec.id.startsWith("bottle-") ? 0.75 : null;
}

/** One row per listing a guest can order tonight, in list order. */
export function rows({ list, unavailable } = {}) {
  const joined = list || joinList().list;
  const raw = JSON.parse(fs.readFileSync(path.join(ROOT, "lists/theatrium.json"), "utf8"));
  const rules = (unavailable || JSON.parse(fs.readFileSync(path.join(ROOT, "data/unavailable.json"), "utf8"))).hidden;
  const hit = hiddenTest(rules);
  const refs = [];
  for (const sec of raw.sections) for (const cat of sec.categories) for (const g of cat.groups)
    for (const it of g.items) refs.push(it.ref);
  const out = [];
  let i = 0;
  for (const sec of joined.sections)
    for (const cat of sec.categories)
      for (const g of cat.groups)
        for (const item of g.items) {
          const ref = refs[i++] || "";
          if (item.price == null || hit(item, sec.id)) continue;
          const l = litres(sec, cat, item);
          const glass = sec.id === "glass";
          out.push({
            naziv: [item.producer, item.name].filter(Boolean).join(" ") + (glass ? " (čaša)" : ""),
            sifra: ref + (glass ? "@casa" : item.vol ? "@" + item.vol : ""),
            marka: item.producer || "",
            neto_kolicina: l,
            jedinica_mjere: l == null ? "" : "l",
            maloprodajna_cijena: item.price,
            cijena_za_jedinicu_mjere: null,   /* not a prepacked retail good */
            barkod: "",
            ean_barkod: "",
            /* only a base price Filho decided (it carries its day); the old
               10.09.2026 seed is not the 2.5.2025. price the law asks for */
            bazna_cijena: item.anchorDate ? item.anchor : null,
            bazna_datum: item.anchorDate || null,
          });
        }
  return out;
}

export const COLUMNS = ["naziv", "sifra", "marka", "neto_kolicina", "jedinica_mjere",
  "maloprodajna_cijena", "cijena_za_jedinicu_mjere", "barkod", "ean_barkod", "bazna_cijena"];

export const digest = (r) =>
  "sha256:" + createHash("sha256").update(JSON.stringify(r)).digest("hex").slice(0, 32);

const money = (n) => (n == null ? "" : Number(n).toFixed(2));
const qty = (n) => (n == null ? "" : String(n));
const value = (x, c) =>
  c === "maloprodajna_cijena" || c === "bazna_cijena" || c === "cijena_za_jedinicu_mjere" ? money(x[c])
  : c === "neto_kolicina" ? qty(x[c]) : x[c] ?? "";
const cell = (v) => (/[";\r\n]/.test(String(v)) ? '"' + String(v).replace(/"/g, '""') + '"' : String(v));
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** čl. 3 st. 2 order, čl. 6 st. 6-7: UTF-8 (no BOM: a parser reads the first
 *  column name, not Excel), ";" between columns. Dot decimals. */
export function csv(r) {
  return [COLUMNS.join(";"), ...r.map((x) => COLUMNS.map((c) => cell(value(x, c))).join(";"))].join("\r\n") + "\r\n";
}

export function xml(r, stamp) {
  const body = r.map((x) => "  <roba>\n" + COLUMNS.map((c) => {
    const v = value(x, c);
    if (c === "bazna_cijena" && x.bazna_datum) return `    <${c} datum="${x.bazna_datum}">${esc(v)}</${c}>`;
    return `    <${c}>${esc(v)}</${c}>`;
  }).join("\n") + "\n  </roba>").join("\n");
  return ['<?xml version="1.0" encoding="UTF-8"?>',
    `<cjenik obveznik="${esc(ISSUER.obveznik)}" oib="${ISSUER.oib}" prodajno_mjesto="${esc(ISSUER.objekt)}, ${esc(ISSUER.adresa)}"`,
    `        vrsta="roba" valuta="EUR" pdv_ukljucen="da" objavljeno="${stamp.iso}" broj_stavki="${r.length}" sazetak="${digest(r)}">`,
    body, "</cjenik>", ""].join("\n");
}

/** GGGGMMDD_SSMM in Zagreb time, plus the ISO instant. */
export function stampOf(date) {
  const p = Object.fromEntries(new Intl.DateTimeFormat("en-GB", { timeZone: "Europe/Zagreb",
    year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", hourCycle: "h23" })
    .formatToParts(date).map((x) => [x.type, x.value]));
  return { name: `${p.year}${p.month}${p.day}_${p.hour}${p.minute}`, iso: date.toISOString() };
}

export const fileBase = (n, stamp) => `${ISSUER.oib}_${ISSUER.mjesto}_ROBA_${n}_${stamp.name}`;

/** Pure: given the previous manifest, the new rows' digest and now, the next
 *  manifest. A new file only when the content changed; the replaced one gets
 *  its `replaced` time and is kept RETAIN_DAYS from then. */
export function nextManifest(prev, dig, now, count) {
  const files = ((prev && prev.files) || []).map((f) => ({ ...f }));
  const cur = files.find((f) => !f.replaced);
  const keepAfter = now.getTime() - RETAIN_DAYS * 86400000;
  const kept = (fs_) => fs_.filter((f) => !f.replaced || Date.parse(f.replaced) >= keepAfter);
  if (cur && cur.digest === dig) return { manifest: { ...prev, files: kept(files) }, changed: false };
  const stamp = stampOf(now);
  const seq = ((prev && prev.seq) || 0) + 1;
  if (cur) cur.replaced = stamp.iso;
  const f = { base: fileBase(seq, stamp), published: stamp.iso, digest: dig, stavki: count };
  return { manifest: { seq, files: kept([f, ...files]) }, changed: true, stamp };
}

