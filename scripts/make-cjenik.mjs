/* The price list as a machine can read it — /cjenik/ on the site.

   Pravilnik o načinu objave cjenika proizvoda (NN 132/2026-1584), in force
   17.11.2026, on the basis of Zakon o zaštiti potrošača čl. 7 st. 9 and 12:

     čl. 3   the list is on the trader's own website; ten columns for goods in
             a fixed order; a changed list goes up by 11:00 on the day of the
             change; a replaced list stays reachable for 15 days
     čl. 6   .xml or .csv (optionally zipped), UTF-8, columns split by ";",
             published at the same place on the site as the one it replaces,
             and named <OIB>_<sales point>_<goods|services>_<n>_<GGGGMMDD_SSMM>

   We publish drinks as GOODS (roba). That matches the reading the base price
   already takes — food and drink get 2.5.2025. as goods do (Pravilnik
   1583 čl. 3) — and the two must not contradict each other. A wine poured by
   the glass is its own line with its own measure.

   Generated by the deploy, never committed. `--site <dir>` writes
   <dir>/cjenik/ and is what scripts/site-files.sh calls: the deploy is the
   one moment every change passes through (a price edited in /admin, an 86, a
   new wine), so the list on the site cannot be older than the list on the
   tablets. The 15-day archive lives on the site itself: the previous deploy's
   manifest.json says which files are still owed, and they are fetched back
   from the live site and republished with the new one. A first deploy (404)
   starts a fresh archive; any other failure stops the deploy rather than
   silently dropping a file the law says must stay up.

   86'd wines are left out (owner, 2026-10-03): what is not offered tonight
   has no price on offer.

     node scripts/make-cjenik.mjs                 # print the rows, write nothing
     node scripts/make-cjenik.mjs --site _site    # what the deploy runs
     CJENIK_LIVE=none node scripts/make-cjenik.mjs --site _site   # offline: no archive
*/
